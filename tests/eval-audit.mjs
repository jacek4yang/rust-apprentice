import assert from "node:assert/strict";
import { auditTrace, reportStatus } from "./lib/eval-audit.mjs";
const spec = { name: "context-many-notes", skill: "continue", mode: "read" };
const init = { type: "system", subtype: "init", cwd: "/tmp/example", model: "test-model" };
const tool = (name, input, id = "call") => ({ type: "assistant", message: { content: [{ type: "tool_use", name, input, id }] } });
const skill = tool("Skill", { skill: "rust-apprentice:rust-learn-continue" }, "skill");
assert.deepEqual(auditTrace([init, skill], spec).errors, []);
assert.ok(auditTrace([init], spec).errors.length);
assert.ok(auditTrace([init, skill, tool("Write", { file_path: "/tmp/example/state/progress.md" })], spec).errors.length);
assert.ok(auditTrace([init, skill, tool("Read", { file_path: "/tmp/example/notes/topic.md" })], spec).errors.length);
assert.ok(auditTrace([init, skill, tool("Grep", { path: "/tmp/example" })], spec).errors.length);
assert.ok(auditTrace([init, skill, tool("Grep", { path: "." })], spec).errors.length);
assert.ok(auditTrace([init, skill, tool("Read", { file_path: "state/../notes/topic.md" })], spec).errors.length);
assert.ok(auditTrace([init, skill, tool("Agent", { prompt: "read all history" })], spec).errors.length);
assert.ok(auditTrace([init, skill, tool("Read", { file_path: "/plugin/skills/x/references/curriculum/networking.md" }, "a"), tool("Read", { file_path: "/plugin/skills/x/references/curriculum/security.md" }, "b")], spec).errors.length);
const read = tool("Read", { file_path: "/tmp/example/state/log.md" });
const result = { type: "user", message: { content: [{ type: "tool_result", tool_use_id: "call", content: "line\n".repeat(401) }] } };
assert.ok(auditTrace([init, skill, read, result], spec).errors.length);
const good = { cases: [{ arms: { with: [{ score: 1, graders: [{ name: "skill-loaded", passed: true }] }] } }] };
assert.equal(reportStatus(good, 1), "passed");
assert.equal(reportStatus(good, 3), "infrastructure-failure");
assert.equal(reportStatus({ ...good, partial: true }, 1), "infrastructure-failure");
const failed = structuredClone(good);
failed.cases[0].arms.with[0].graders.push({ name: "no-write", passed: false });
assert.equal(reportStatus(failed, 1), "product-failure", "a high mean must not hide mutation");
failed.cases[0].arms.with[0].error = "scaffold failed";
assert.equal(reportStatus(failed, 1), "infrastructure-failure");
console.log("Eval audit counterexamples passed: missing invocation, mutation, cold reads, broad search, domain/budget overflow and infrastructure failures.");
